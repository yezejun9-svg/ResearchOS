const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { chromium } = require('C:/Users/yqyyds/AppData/Local/Python/pythoncore-3.14-64/Lib/site-packages/playwright/driver/package')

async function main() {
  const receipt = 'D:/作品集/ResearchOS/research-os/execution/v2.4/receipts/W05/W05-99/normal_model_configuration_ui_codex/20261012-current-chat'
  const browser = await chromium.launch({ headless: true })
  const page = await browser.newPage({ viewport: { width: 1240, height: 900 } })
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  try {
    await page.goto('http://127.0.0.1:5178/.local/model-config-harness.html')
    await page.getByRole('heading', { name: '模型配置' }).waitFor()
    await page.getByLabel('提供方 ID').fill('ollama')
    await page.getByLabel('模型 ID').fill('qwen3:4b-instruct')
    await page.getByLabel('API 基础地址').fill('http://127.0.0.1:11434/v1')
    await page.getByRole('button', { name: '保存模型配置' }).click()
    await page.getByText('配置已保存（修订 1）', { exact: false }).waitFor()
    const first = await page.evaluate(() => window.__calls.find(item => item.method === 'host.configure'))
    assert.deepEqual(Object.keys(first.payload).sort(), ['base_url', 'config_revision', 'credential_ref', 'model_id', 'provider_id'])
    assert.deepEqual(first.payload, { config_revision: 1, provider_id: 'ollama', base_url: 'http://127.0.0.1:11434/v1', model_id: 'qwen3:4b-instruct', credential_ref: null })
    assert.equal(await page.getByText('运行时资格尚未确认', { exact: false }).count() > 0, true)
    await page.screenshot({ path: path.join(receipt, 'browser-config-saved.png'), fullPage: true })
    await page.evaluate(() => { window.__reject = true })
    await page.getByLabel('模型 ID').fill('bad-model')
    await page.getByRole('button', { name: '保存模型配置' }).click()
    await page.getByRole('alert').getByText('CONFIGURATION_ENDPOINT：address rejected', { exact: false }).waitFor()
    assert.equal(await page.getByLabel('模型 ID').inputValue(), 'bad-model')
    const calls = await page.evaluate(() => window.__calls)
    assert.equal(calls.filter(item => item.method === 'host.configure').length, 2)
    await page.screenshot({ path: path.join(receipt, 'browser-config-error.png'), fullPage: true })
    await page.evaluate(() => { window.__reject = false; window.__ackOnce = true })
    await page.getByLabel('模型 ID').fill('ack-model')
    await page.getByRole('button', { name: '保存模型配置' }).click()
    await page.getByRole('button', { name: '继续同一配置命令' }).waitFor()
    assert.equal(await page.getByLabel('模型 ID').isDisabled(), true)
    await page.getByRole('button', { name: '继续同一配置命令' }).click()
    await page.getByText('配置已保存（修订 2）', { exact: false }).waitFor()
    const finalCalls = await page.evaluate(() => window.__calls)
    const configure = finalCalls.filter(item => item.method === 'host.configure')
    assert.equal(configure.length, 4)
    assert.deepEqual(configure[2].payload, configure[3].payload)
    assert.deepEqual(errors, [])
    await page.screenshot({ path: path.join(receipt, 'browser-config-ack-replay.png'), fullPage: true })
    const report = { schema: 'w05-model-config-browser-fixture/1', status: 'PASS', kind: 'BROWSER_RENDERER_WITH_SYNTHETIC_BRIDGE', cases: ['save-null-credential-exact-payload', 'visible-unqualified-state', 'backend-error-and-input-retention', 'acknowledged-exact-payload-replay'], project_id: 'project-browser-fixture', calls: finalCalls, page_errors: errors, model_calls: 0, external_calls: 0 }
    fs.writeFileSync(path.join(receipt, 'browser-config-test.json'), JSON.stringify(report, null, 2) + '\n')
    console.log(JSON.stringify({ status: report.status, cases: report.cases, model_calls: 0 }))
  } finally { await browser.close() }
}
main().catch(error => { console.error(error.stack || error); process.exitCode = 1 })
