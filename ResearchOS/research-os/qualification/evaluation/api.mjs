import fs from 'node:fs';
import net from 'node:net';
process.env.PROMPTFOO_DISABLE_TELEMETRY='true';
process.env.PROMPTFOO_DISABLE_UPDATE_CHECK='true';
process.env.PROMPTFOO_DISABLE_SHARING='true';
process.env.PROMPTFOO_CONFIG_DIR=process.cwd();
const original=net.Socket.prototype.connect;
net.Socket.prototype.connect=function(...args){const arg=args[0];process.stderr.write('EGRESS_ATTEMPT '+JSON.stringify({api:'Socket.connect',destination:typeof arg==='object'?{host:arg.host,port:arg.port}:arg})+'\n');return original.apply(this,args)};
const {evaluate}=await import('./node_modules/promptfoo/dist/src/index.js');
const config=JSON.parse(fs.readFileSync(new URL('./config.json',import.meta.url),'utf8'));
const results=await evaluate(config,{cache:false,writeLatestResults:false,showProgressBar:false});
fs.writeFileSync('export-api.json',JSON.stringify(results));
