"""Erratum for the mutation counts quoted in W04-02 commit prose.

Written as a file rather than a heredoc because the previous attempt died on console quoting. The
numbers come from the note generator's own output, so this record cannot drift from the evidence.
"""
import datetime
import io
import json
import subprocess

note = json.load(io.open("execution/v2.4/receipts/W04/W04-02/progress_note_1.json", encoding="utf-8"))
cases = note["mutations"]["all_passes"]["cases"]
caught = len(note["mutations"]["all_passes"]["caught"])
survived = note["mutations"]["all_passes"]["survived"]
head = subprocess.run(["git", "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()

doc = {
 "record": "erratum - mutation counts quoted in W04-02 commit messages",
 "written_by": "qoder-desktop:/root/construction",
 "written_at": datetime.datetime.now(datetime.timezone.utc).isoformat(),
 "step_id": "W04-02",
 "head_at_erratum": head,
 "wrong_statements": [
  {"commit": "636c9e04", "quoted": "11 of 12 mutations die on named ids",
   "actual": "the note that commit carried computed 12 of 13", "severity": "immaterial but wrong"},
  {"commit": "419c2e75", "quoted": "the current set is 14 of 15 across three passes",
   "actual": "the note re-computed by that same run gives %d of %d" % (caught, cases),
   "severity": "immaterial but wrong"}],
 "authoritative_numbers": {
   "mutation_cases": cases, "caught": caught, "survived": survived,
   "assertions": note["check_program"]["assertions"],
   "ctx_assertions": note["check_program"]["ctx_assertions"],
   "chg_assertions": note["check_program"]["chg_assertions"],
   "not_verified": len(note["check_program"]["not_verified"]),
   "source": "progress_note_1.json, generated by .local/note_w0402_third.py from the three "
             "mutation_selfcheck_w0402*.json files and the captured check report"},
 "why_this_happened": "each commit message re-typed a count instead of reading it from the generator - the exact "
   "failure W04-01 was rejected for four times. No code, evidence file or check result is affected.",
 "remedy": "commit messages are history and stay untouched; counts for this card family are taken from the note "
   "generator's own stdout from here on, and a reviewer should read the note rather than prose."}

io.open("execution/v2.4/receipts/W04/W04-02/evidence_erratum_1.json", "w", encoding="utf-8", newline="\n").write(
    json.dumps(doc, indent=1, ensure_ascii=False))
print("erratum written: %d caught of %d cases, %d assertions" % (caught, cases,
                                                                 note["check_program"]["assertions"]))
